import pandas as pd

employees = pd.read_csv("employee-leave-requests-and-timesheets-dataset-v1-csv-employees.csv")
departments = pd.read_csv("employee-leave-requests-and-timesheets-dataset-v1-csv-departments.csv")
timesheets = pd.read_csv("employee-leave-requests-and-timesheets-dataset-v1-csv-timesheets.csv")
weeks = pd.read_csv("employee-leave-requests-and-timesheets-dataset-v1-csv-timesheet_weeks.csv")

print("Employees:", employees.shape)
print("Departments:", departments.shape)
print("Timesheets:", timesheets.shape)
print("Weeks:", weeks.shape)

timesheets.head()

"""Creating one combined dataset so we can analyse employee hours by department and week."""

df = (
    timesheets
    .merge(
        employees,
        left_on="employee_id",
        right_on="id",
        suffixes=("_timesheet", "_employee")
    )
    .merge(
        departments,
        left_on="department_id",
        right_on="id"
    )
    .merge(
        weeks,
        left_on="week_id",
        right_on="id",
        suffixes=("", "_week")
    )
)

display(df.head())

"""Total hours by department"""

department_summary = (
    df.groupby("department_name")
    .agg(
        total_hours=("hours_worked", "sum"),
        employee_count=("employee_id", "nunique"),
        average_utilisation=("utilisation", "mean")
    )
    .round(2)
    .reset_index()
    .sort_values("total_hours", ascending=False)
)

display(department_summary)

import matplotlib.pyplot as plt

plt.figure(figsize=(10, 5))

plt.bar(
    department_summary["department_name"],
    department_summary["total_hours"],
    color="steelblue"
)

plt.title("Total Hours Worked by Department")
plt.xlabel("Department")
plt.ylabel("Total Hours")
plt.xticks(rotation=45, ha="right")
plt.tight_layout()
plt.show()

# hourly rates for each employee
employee_rates = employees[["id", "first_name", "last_name"]].copy()

employee_rates = employee_rates.rename(
    columns={"id": "employee_id"}
)

employee_rates["hourly_rate"] = 30.00  # Example rate

# Join rates to the timesheet data
cost_df = df.merge(
    employee_rates[["employee_id", "hourly_rate"]],
    on="employee_id",
    how="left"
)

# Calculate estimated labour cost
cost_df["labour_cost"] = (
    cost_df["hours_worked"] * cost_df["hourly_rate"]
)

display(
    cost_df[
        ["first_name", "last_name", "hours_worked",
         "hourly_rate", "labour_cost"]
    ].head()
)

"""Table showing each department's total recorded hours, estimated labour cost, and number of employees."""

cost_summary = (
    cost_df.groupby("department_name", as_index=False)
    .agg(
        total_hours=("hours_worked", "sum"),
        total_labour_cost=("labour_cost", "sum"),
        employee_count=("employee_id", "nunique")
    )
)

cost_summary["total_labour_cost"] = (
    cost_summary["total_labour_cost"].round(2)
)

display(cost_summary.sort_values(
    "total_labour_cost", ascending=False
))

import matplotlib.pyplot as plt
import seaborn as sns

chart_title = "Labour Cost by Department"
bar_color = "#f85b6b"
background_color = "#F5F7FA"

sns.set_theme(style="whitegrid")

fig, ax = plt.subplots(figsize=(11, 6))
fig.patch.set_facecolor(background_color)
ax.set_facecolor(background_color)

data = cost_summary.sort_values("total_labour_cost")

bars = ax.barh(
    data["department_name"],
    data["total_labour_cost"],
    color=bar_color,
    edgecolor="white",
    height=0.65
)


ax.bar_label(
    bars,
    fmt="%.2f",
    padding=6,
    fontsize=10
)

ax.set_title(chart_title, fontsize=17, fontweight="bold", pad=18)
ax.set_xlabel("Estimated Labour Cost", fontsize=12)
ax.set_ylabel("Department", fontsize=12)

ax.spines[["top", "right", "left"]].set_visible(False)
ax.grid(axis="x", alpha=0.25)
ax.grid(axis="y", visible=False)

plt.tight_layout()
plt.show()

weekly_summary = (
    cost_df.groupby("week_starts_on", as_index=False)
    .agg(
        total_hours=("hours_worked", "sum"),
        total_labour_cost=("labour_cost", "sum")
    )
    .sort_values("week_starts_on")
)

display(weekly_summary.round(2))

plt.figure(figsize=(10, 5))

plt.plot(
    weekly_summary["week_starts_on"],
    weekly_summary["total_labour_cost"],
    marker="o",
    color="darkorange"
)

plt.title("Weekly Estimated Labour Costs")
plt.xlabel("Week Starting")
plt.ylabel("Estimated Labour Cost")
plt.xticks(rotation=45)
plt.grid(True, alpha=0.3)

plt.tight_layout()
plt.show()

employee_weekly = (
    cost_df.groupby(
        ["employee_id", "first_name", "last_name",
         "week_starts_on", "contracted_hours"],
        as_index=False
    )
    .agg(hours_worked=("hours_worked", "sum"))
)

employee_weekly["hours_difference"] = (
    employee_weekly["hours_worked"]
    - employee_weekly["contracted_hours"]
)

employee_weekly["hours_status"] = employee_weekly[
    "hours_difference"
].apply(
    lambda x: "Above contracted hours" if x > 0
    else "Below contracted hours" if x < 0
    else "Equal to contracted hours"
)

display(employee_weekly.round(2))

"""Lets Export"""

with pd.ExcelWriter("Timesheet_Cost_Analysis.xlsx") as writer:
    df.to_excel(
        writer, sheet_name="Detailed Timesheets", index=False
    )
    department_summary.to_excel(
        writer, sheet_name="Department Hours", index=False
    )
    cost_summary.to_excel(
        writer, sheet_name="Department Costs", index=False
    )
    weekly_summary.to_excel(
        writer, sheet_name="Weekly Trends", index=False
    )
    employee_weekly.to_excel(
        writer, sheet_name="Employee Hours", index=False
    )

print("Final report created successfully!")

